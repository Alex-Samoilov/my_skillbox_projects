#include <iostream>
#include <string>
using namespace std;
enum notes {
  unknown = 0,
  DO = 1,
  RE = 2,
  MI = 4,
  FA = 8,
  SOL = 16,
  LA = 32,
  SI = 64
};
void printNote(notes NFlag) {
  if (NFlag == DO) {
    cout << "DO ";
  } else if (NFlag == RE) {
    cout << "RE ";
  } else if (NFlag == MI) {
    cout << "MI ";
  } else if (NFlag == FA) {
    cout << "FA ";
  } else if (NFlag == SOL) {
    cout << "SOL ";
  } else if (NFlag == LA) {
    cout << "LA ";
  } else if (NFlag == SI) {
    cout << "SI ";
  }
}
int main() {
  string chord;
  cout << "Input numbers from 1 to 7: ";
  cin >> chord;
  int chordMask = 0; 
  for (int i = 0; i < chord.length(); i++) {
    int noteIndex = chord[i] - '1'; 
    if (noteIndex >= 0 && noteIndex <= 6) { 
      chordMask |= (1 << noteIndex); 
    }
  }
  cout << "Notes in chord: ";
  if (chordMask & DO) {
    cout << "DO ";
  }
  if (chordMask & RE) {
    cout << "RE ";
  }
  if (chordMask & MI) {
    cout << "MI ";
  }
  if (chordMask & FA) {
    cout << "FA ";
  }
  if (chordMask & SOL) {
    cout << "SOL ";
  }
  if (chordMask & LA) {
    cout << "LA ";
  }
  if (chordMask & SI) {
    cout << "SI ";
  }
  cout << endl;
  return 0;
}

